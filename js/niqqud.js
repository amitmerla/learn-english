const HE = '\\u05D0-\\u05EA\\u0591-\\u05C7';
const RE = new RegExp(`(?<![${HE}])(${Object.keys(POINTED).sort((a, b) => b.length - a.length).join('|')})(?![${HE}])`, 'g');
const MARK = /[֑-ׇֽֿׁׂׅׄ]/;

/** Plain Hebrew → the same text with niqqud on the words a voice might misread. */
export const withNiqqud = text => text.replace(RE, w => POINTED[w]);

/** A character index in the pointed text → the same place in the plain text. */
export function plainIndex(pointed, i) {
    let marks = 0;
    for (let k = 0; k < i && k < pointed.length; k++) if (MARK.test(pointed[k])) marks += 1;
    return i - marks;
}
